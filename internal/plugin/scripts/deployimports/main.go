//go:build ignore

// deployimports 生成 cmd/deploy-helper/imports_gen.go。
//
// 部署目标通过 init 注册；新增目标时只需创建 deploy/providers/<id>，然后
// 重新生成本文件，避免多人同时修改 cmd/deploy-helper/main.go 的导入块。
// panels 由 main.go 显式导入并注册多个规范 ID，因此不在此处生成。
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

const (
	providersDir = "deploy/providers"
	outputPath   = "cmd/deploy-helper/imports_gen.go"
	modulePath   = "lactssl/internal/plugin"
)

func main() {
	entries, err := os.ReadDir(providersDir)
	check(err)
	var ids []string
	for _, entry := range entries {
		if !entry.IsDir() || entry.Name() == "panels" || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		ids = append(ids, entry.Name())
	}
	sort.Strings(ids)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/deployimports; DO NOT EDIT.\n\n")
	buf.WriteString("package main\n\nimport (\n")
	for _, id := range ids {
		fmt.Fprintf(&buf, "\t_ %q\n", modulePath+"/deploy/providers/"+id)
	}
	buf.WriteString(")\n")

	raw, err := format.Source(buf.Bytes())
	check(err)
	check(os.WriteFile(outputPath, raw, 0o644))
	fmt.Printf("deployimports: %d providers -> %s\n", len(ids), outputPath)
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "deployimports: "+err.Error())
		os.Exit(1)
	}
}
